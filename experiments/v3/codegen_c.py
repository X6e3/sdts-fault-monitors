"""Emit a C header with the offline tables of a v3 template (for experiments/v3/c/v3_state.c).

Per direction i the run-time support is  min over entries e of  sum_j lam[e][j] * h[idx[e][j]]  + PAD_i,
with PAD_i a per-direction constant that bounds, for the chosen arithmetic (float32 or float64):
  rounding of the 3-term dot product (gamma * sum|lam| * HMAX), the table residual (res * CAP) and the
  rounding of lam itself to the stored precision (|lam - fl(lam)| * HMAX * 3).
CAP = 2.2 bounds |s_c| (the clamps keep every coordinate in the shifted box [-2, 2]) and HMAX = sqrt(3) CAP
bounds |h_i| for unit directions while the set is nonempty. The rounded lam add |lam - fl(lam)| ||d||_1 CAP.
usage: python codegen_c.py KIND [--N n] [--L l] --out FILE [--real float|double]
"""
import argparse
import math
import os
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
import template_state as V  # noqa: E402


def build(kind, N, L, real):
    tp = V.Template(V.directions(kind, N=N, L=L), invariant=True)
    eps = np.finfo(np.float32 if real == "float" else np.float64).eps
    gamma = 6 * eps / (1 - 6 * eps)
    caps = tp.cap_inv.copy()
    for c in range(3):
        caps[tp.ip[c]] = min(caps[tp.ip[c]], V.HI)
        caps[tp.im[c]] = min(caps[tp.im[c]], -V.LO)
    cap = 2.2                                           # |s_c| <= 2 inside the clamped box, with margin
    hmax = math.sqrt(3) * cap                           # |h_i| <= ||d_i||_1 |s|_inf for a nonempty set
    groups = tp.pred + tp.supp_as                       # n prediction groups, then +e2 and -e2 supports
    idx, lam, starts, pads = [], [], [0], []
    for g in groups:
        t, l, ls, res = g
        lam_r = l.astype(np.float32 if real == "float" else np.float64)
        lam_err = np.abs(l - lam_r.astype(np.float64)).sum(axis=1)
        pad = float(np.max(gamma * ls * hmax + res * cap + lam_err * math.sqrt(3) * cap))
        pads.append(math.nextafter(pad * 1.01 + 4 * eps * hmax, math.inf))
        idx += t.tolist()
        lam += lam_r.tolist()
        starts.append(starts[-1] + len(t))
    return tp, hmax, idx, lam, starts, pads


def up_to(x, real):
    """x rounded upward to the target precision (exact zeros stay zero)."""
    if real == "double":
        return float(x)
    f = np.float32(x)
    if float(f) < x:
        f = np.nextafter(f, np.float32(np.inf))
    return float(f)


def emit(tp, hmax, idx, lam, starts, pads, real, name):
    n, m = tp.n, len(idx)
    f = "f" if real == "float" else ""
    num = lambda x: (f"{np.float32(x)!r}{f}".replace("np.float32(", "").replace(")", "") if real == "float" else f"{x!r}")
    upn = lambda x: num(up_to(x, real))
    out = [f"/* generated by experiments/v3/codegen_c.py ({name}); do not edit */",
           "#ifndef V3_TABLES_H", "#define V3_TABLES_H", "#include <stdint.h>",
           f"typedef {real} v3_real;",
           f"#define V3_N {n}", f"#define V3_ENTRIES {m}", f"#define V3_GROUPS {n + 2}",
           f"#define V3_IP2 {tp.ip[1]}", f"#define V3_IM2 {tp.im[1]}",
           f"#define V3_HMAX {upn(hmax)}",
           "static const uint8_t V3_IDX[V3_ENTRIES][3] = {" + ",".join("{%d,%d,%d}" % tuple(r) for r in idx) + "};",
           "static const v3_real V3_LAM[V3_ENTRIES][3] = {" + ",".join("{" + ",".join(num(x) for x in r) + "}" for r in lam) + "};",
           "static const uint16_t V3_START[V3_GROUPS + 1] = {" + ",".join(str(s) for s in starts) + "};",
           "static const v3_real V3_PAD[V3_GROUPS] = {" + ",".join(upn(p) for p in pads) + "};",
           "static const v3_real V3_RHOPAD[V3_N] = {" + ",".join(upn(math.nextafter(x, math.inf) if x else 0.0) for x in tp.rho_pad) + "};",
           "static const v3_real V3_CAP[V3_N] = {" + ",".join(upn(x) for x in _caps(tp)) + "};",
           "static const v3_real V3_H0[V3_N] = {" + ",".join(upn(x) for x in tp.clamp(tp.h0)) + "};",
           "#endif", ""]
    return "\n".join(out)


def _caps(tp):
    caps = tp.cap_inv.copy()
    for c in range(3):
        caps[tp.ip[c]] = min(caps[tp.ip[c]], V.HI)
        caps[tp.im[c]] = min(caps[tp.im[c]], -V.LO)
    return [float(x) for x in caps]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("kind")
    ap.add_argument("--N", type=int, default=4)
    ap.add_argument("--L", type=int, default=0)
    ap.add_argument("--real", choices=("float", "double"), default="float")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    tp, hmax, idx, lam, starts, pads = build(a.kind, a.N, a.L, a.real)
    if max(max(r) for r in idx) > 255 or starts[-1] > 65535:
        raise SystemExit("table too large for uint8/uint16 indices")
    a.out.write_text(emit(tp, hmax, idx, lam, starts, pads, a.real, f"{a.kind} N={a.N} L={a.L} {a.real}"))
    flash = len(idx) * (3 + 3 * (4 if a.real == "float" else 8)) + (len(starts) * 2) + (len(pads) + 3 * tp.n) * (4 if a.real == "float" else 8)
    print(f"n={tp.n} entries={len(idx)} flash~{flash} B  state RAM={tp.n * (4 if a.real == 'float' else 8)} B + S (2 doubles)")


if __name__ == "__main__":
    main()
